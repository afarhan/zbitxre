// si5351_golden.h — what the radio's original si5351v2.c wrote to the chip.
//
// Each row is one retune, captured on a zbitx by running the original driver
// against a recording I2C bus: the eight PLL registers, the eight divider
// registers, then the clock's control register. The rows cover the BFO, the
// receiver's oscillator at both ends of its range, a PLL that lands on a whole
// multiple of the crystal, and the lowest and highest outputs accepted.

